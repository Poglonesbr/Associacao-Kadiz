export function labelFor(value: string | null | undefined): string {
  if (!value) return "—";
  return (
    enumLabels[value] ??
    value
      .toLocaleLowerCase("pt-BR")
      .replaceAll("_", " ")
      .replace(/^([a-zà-ÿ])/i, (letter) => letter.toLocaleUpperCase("pt-BR"))
  );
}
